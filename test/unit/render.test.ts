import { beforeAll, describe, expect, it } from "vitest";
import { layoutDiagram } from "../../src/layout/index.js";
import { validateDiagram } from "../../src/model/index.js";
import { renderHtml } from "../../src/render/html.js";
import { renderSvg } from "../../src/render/svg.js";
import { ICONS } from "../../src/render/generated/icons.js";
import type { Scene } from "../../src/scene.js";
import { VERSION } from "../../src/version.js";

let scene: Scene;

beforeAll(async () => {
  const { diagram, issues } = validateDiagram({
    type: "architecture",
    title: 'Orders <&"> flow',
    description: "Checkout & fulfilment",
    theme: "dark",
    nodes: [
      { id: "web", label: "Web App", kind: "client" },
      {
        id: "api",
        label: "Orders API",
        kind: "service",
        note: "Handles checkout",
        source: "src/api.ts:12",
      },
      { id: "db", label: "PostgreSQL", kind: "database" },
      { id: "queue", label: "Events", kind: "queue" },
    ],
    groups: [{ id: "vpc", label: "Production VPC", children: ["api", "db", "queue"] }],
    edges: ["web -> api: HTTPS", "api -> db: SQL", "api ~> queue: order.created"],
  });
  expect(issues.filter((i) => i.severity === "error")).toEqual([]);
  scene = await layoutDiagram(diagram!);
});

const count = (s: string, re: RegExp) => (s.match(re) ?? []).length;

describe("renderSvg", () => {
  it("emits one t-node per node with its id and kind", () => {
    const svg = renderSvg(scene);
    expect(count(svg, /class="t-node"/g)).toBe(scene.nodes.length);
    for (const n of scene.nodes) expect(svg).toContain(`data-id="${n.id}" data-kind="${n.kind}"`);
  });

  it("emits groups before edges before nodes", () => {
    const svg = renderSvg(scene);
    expect(count(svg, /class="t-group"/g)).toBe(1);
    expect(svg.indexOf('class="t-group"')).toBeLessThan(svg.indexOf('class="t-edge '));
    expect(svg.indexOf('class="t-edge ')).toBeLessThan(svg.indexOf('class="t-node"'));
  });

  it("tags every edge path with the edge id", () => {
    const svg = renderSvg(scene);
    for (const e of scene.edges) expect(svg).toContain(`data-edge="${e.id}"`);
    expect(count(svg, /<path class="t-edge [^>]*data-edge="/g)).toBe(scene.edges.length);
  });

  it("emits one edge path per edge with the matching style class", () => {
    const svg = renderSvg(scene);
    expect(count(svg, /<path class="t-edge /g)).toBe(scene.edges.length);
    expect(count(svg, /class="t-edge t-edge-sync"/g)).toBe(2);
    expect(count(svg, /class="t-edge t-edge-async"/g)).toBe(1);
    expect(svg).toContain('data-from="api" data-to="queue"');
    expect(count(svg, /<marker /g)).toBe(1);
  });

  it("renders edge labels", () => {
    const svg = renderSvg(scene);
    expect(svg).toContain("HTTPS");
    expect(svg).toContain("order.created");
  });

  it("escapes the title in svg title and root label", () => {
    const svg = renderSvg(scene);
    expect(svg).toContain("<title");
    expect(svg).toContain("Orders &lt;&amp;&quot;&gt; flow</title>");
    expect(svg).not.toContain('Orders <&">');
    expect(svg).toContain("<desc");
    expect(svg).toContain("Checkout &amp; fulfilment");
  });

  it("emits icons only for kinds in use", () => {
    const svg = renderSvg(scene);
    expect(svg).toContain(ICONS["database"]);
    expect(svg).toContain(ICONS["inbox"]);
    expect(svg).not.toContain(ICONS["globe"]);
  });

  it("puts note and source in the node tooltip", () => {
    const svg = renderSvg(scene);
    const api = svg.slice(svg.indexOf('data-id="api" data-kind'));
    const tip = /<desc>([^<]*)<\/desc>/.exec(api)![1]!;
    expect(svg.match(/<title/g)).toHaveLength(1);
    expect(tip).toContain("Handles checkout");
    expect(tip).toContain("src/api.ts:12");
  });

  it("disables kerning and ligatures", () => {
    const svg = renderSvg(scene);
    expect(svg).toContain("font-kerning: none");
    expect(svg).toContain("font-variant-ligatures: none");
  });

  it("is balanced and has no bare ampersands", () => {
    const svg = renderSvg(scene);
    expect(count(svg, /<svg\b/g)).toBeGreaterThanOrEqual(1);
    expect(count(svg, /<svg\b/g)).toBe(count(svg, /<\/svg>/g));
    expect(svg).not.toMatch(/&(?!(amp|lt|gt|quot|apos|#\d+);)/);
  });

  it("is deterministic", () => {
    expect(renderSvg(scene)).toBe(renderSvg(scene));
  });
});

describe("renderHtml", () => {
  it("starts with the doctype and the attribution comment", () => {
    const html = renderHtml(scene);
    expect(html.startsWith("<!doctype html>\n<!--")).toBe(true);
    expect(html).toContain(`Generated by trazo ${VERSION}.`);
    expect(html).toContain("Lucide (ISC License)");
    expect(html).toContain("Feather (MIT License, Copyright (c) 2013-present Cole Bemis)");
    expect(html).toContain(
      "Inter (SIL Open Font License 1.1, Copyright 2016 The Inter Project Authors)",
    );
  });

  it("sets generator meta, theme and escaped title", () => {
    const html = renderHtml(scene);
    expect(html).toContain(`<meta name="generator" content="trazo ${VERSION}">`);
    expect(html).toContain('<html lang="en" data-theme="dark">');
    expect(html).toContain("<title>Orders &lt;&amp;&quot;&gt; flow</title>");
    expect(renderHtml({ ...scene, theme: "light" })).toContain('data-theme="light"');
  });

  it("embeds both font weights as data URLs", () => {
    const html = renderHtml(scene);
    expect(count(html, /@font-face/g)).toBe(2);
    expect(count(html, /data:font\/woff2;base64,/g)).toBe(2);
  });

  it("has the full screen and theme buttons", () => {
    const html = renderHtml(scene);
    expect(html).toContain('id="fullscreen" aria-label="Enter full screen"');
    expect(html).toContain("requestFullscreen");
  });

  it("labels the theme button with the theme it switches to", () => {
    expect(renderHtml({ ...scene, theme: "dark" })).toContain(
      'id="theme" aria-label="Switch to light theme"',
    );
    expect(renderHtml({ ...scene, theme: "light" })).toContain(
      'id="theme" aria-label="Switch to dark theme"',
    );
  });

  it("shows the sun in dark mode and the moon in light mode", () => {
    const html = renderHtml(scene);
    expect(html).toContain(
      '[data-theme="dark"] .i-moon, :root:not([data-theme="dark"]) .i-sun { display: none; }',
    );
  });

  it("swaps the full screen icon while in full screen", () => {
    const html = renderHtml(scene);
    expect(html).toContain(
      ".is-fullscreen .i-maximize, :root:not(.is-fullscreen) .i-minimize { display: none; }",
    );
  });

  it("loads nothing from the network", () => {
    const html = renderHtml(scene);
    expect(html).not.toMatch(/src="http/);
    // The only absolute link is the credit anchor, which loads nothing until the reader clicks it.
    expect(html.match(/href="http[^"]*"/g)).toEqual(['href="https://github.com/heidenber/trazo"']);
    expect(html).toMatch(
      /<a href="https:\/\/github\.com\/heidenber\/trazo" target="_blank" rel="noopener noreferrer">/,
    );
    expect(html).not.toMatch(/url\(\s*["']?http/);
  });

  it("is deterministic", () => {
    expect(renderHtml(scene)).toBe(renderHtml(scene));
  });
});
