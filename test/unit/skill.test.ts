import { spawnSync } from "node:child_process";
import { cpSync, mkdtempSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { describe, expect, it } from "vitest";

const root = resolve(__dirname, "../..");
const read = (p: string) => readFileSync(join(root, p), "utf8").replace(/\r\n/g, "\n");
const script = join(root, "scripts/gen-skill.mjs");

function split(source: string) {
  const m = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(source);
  if (!m) throw new Error("no frontmatter");
  const fields = Object.fromEntries(
    m[1]!.split("\n").map((l) => [l.slice(0, l.indexOf(":")), l.slice(l.indexOf(":") + 1).trim()]),
  );
  return { fields, body: m[2]!.trim() };
}

const skill = split(read("skill/SKILL.md"));

describe("skill/SKILL.md", () => {
  it("has name, a one-line description and license", () => {
    expect(skill.fields.name).toBe("trazo");
    expect(skill.fields.description).toBeTruthy();
    expect(skill.fields.description!.length).toBeLessThanOrEqual(300);
    expect(skill.fields.license).toBe("Apache-2.0");
  });

  it("keeps the body within the token budget", () => {
    expect(skill.body.length).toBeLessThanOrEqual(2000);
    expect(Math.ceil(skill.body.length / 4)).toBeLessThanOrEqual(500);
  });

  it("names the four commands of the workflow", () => {
    for (const c of ["trazo example", "trazo schema", "trazo check", "trazo make"]) {
      expect(skill.body).toContain(c);
    }
  });

  it("starts from the example file and keeps work in the current directory", () => {
    expect(skill.body).toContain("`trazo example <type> > diagram.json`");
    expect(skill.body).toContain("current directory");
    expect(skill.body).toContain("`trazo make <file>`");
  });

  it("tells the agent to draw only what it found in the code, with sources and one level of detail", () => {
    expect(skill.body).toContain("read it first and draw only what you found");
    expect(skill.body).toContain("`source`");
    expect(skill.body).toContain("one level of detail");
    expect(skill.body).toContain("ask the user");
    expect(skill.body).toContain("docs/diagrams/");
  });

  it("only mentions real commands", () => {
    const found = [...skill.body.matchAll(/\btrazo ([a-z]+)/g)].map((m) => m[1]);
    expect(found.length).toBeGreaterThan(0);
    for (const c of found) expect(["make", "check", "schema", "example"]).toContain(c);
  });

  it("only names geometry codes that exist", () => {
    const geometry = read("src/check/geometry.ts");
    const codes = [
      "text-overflow",
      "label-overlap",
      "edge-through-node",
      "node-overlap",
      "outside-canvas",
      "outside-group",
    ];
    for (const c of codes) expect(geometry).toContain(`"${c}"`);
    const named =
      skill.body.match(
        /\b(?:text-overflow|label-overlap|edge-through-node|node-overlap|outside-[a-z]+)\b/g,
      ) ?? [];
    expect(named.length).toBeGreaterThan(0);
    for (const c of named) expect(codes).toContain(c);
  });
});

describe("skill/AGENTS.md", () => {
  it("is wrapped in markers and carries the description and body", () => {
    const agents = read("skill/AGENTS.md");
    expect(
      agents.startsWith(
        "<!-- Generated by scripts/gen-skill.mjs from skill/SKILL.md. Do not edit. -->\n<!-- trazo:start -->\n## trazo\n",
      ),
    ).toBe(true);
    expect(agents.endsWith("<!-- trazo:end -->\n")).toBe(true);
    expect(agents).toContain(skill.fields.description!);
    expect(agents).toContain(skill.body);
    expect(agents).not.toContain("license:");
  });

  function sandbox() {
    const dir = mkdtempSync(join(tmpdir(), "trazo-skill-"));
    mkdirSync(join(dir, "skill"));
    cpSync(join(root, "skill/SKILL.md"), join(dir, "skill/SKILL.md"));
    return dir;
  }
  const run = (cwd: string, ...args: string[]) =>
    spawnSync(process.execPath, [script, ...args], { cwd, encoding: "utf8" });

  it("matches what gen-skill produces", () => {
    const dir = sandbox();
    expect(run(dir).status).toBe(0);
    expect(readFileSync(join(dir, "skill/AGENTS.md"), "utf8").replace(/\r\n/g, "\n")).toBe(
      read("skill/AGENTS.md"),
    );
    const check = run(dir, "--check");
    expect(check.status).toBe(0);
    expect(check.stderr).toBe("");
  });

  it("--check fails with a clear message when the file is stale", () => {
    const dir = sandbox();
    run(dir);
    writeFileSync(join(dir, "skill/AGENTS.md"), "stale\n");
    const check = run(dir, "--check");
    expect(check.status).toBe(1);
    expect(check.stderr).toContain("skill/AGENTS.md is out of date; run npm run gen");
  });

  it("rejects a SKILL.md without frontmatter", () => {
    const dir = sandbox();
    writeFileSync(join(dir, "skill/SKILL.md"), "no frontmatter\n");
    const r = run(dir);
    expect(r.status).toBe(1);
    expect(r.stderr).toContain("error: skill/SKILL.md has no frontmatter");
  });
});
