import { readPackageFile, packageInfo, emit } from "./lib.mjs";

const NAMES = [
  "monitor",
  "user",
  "network",
  "server",
  "zap",
  "database",
  "layers",
  "inbox",
  "hard-drive",
  "globe",
  "sun",
  "moon",
  "maximize",
  "minimize",
  "clock",
  "zoom-in",
  "zoom-out",
  "focus",
  "file-code",
  "file-image",
];

// Names that Lucide lists as derived from Feather in its LICENSE file.
const license = readPackageFile("lucide-static", "LICENSE");
const featherLine = license.split("\n").find((l) => l.startsWith("airplay,")) ?? "";
const featherSet = new Set(featherLine.split(",").map((s) => s.trim()));
const derived = NAMES.filter((n) => featherSet.has(n));

const inner = (name) => {
  const svg = readPackageFile("lucide-static", `icons/${name}.svg`);
  const match = /<svg\b[^>]*>([\s\S]*)<\/svg>/.exec(svg);
  if (!match) throw new Error(`unexpected markup in icon ${name}`);
  return match[1]
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean)
    .join("");
};

const version = packageInfo("lucide-static").version;
const entries = NAMES.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(inner(n))},`);

const out = `// SPDX-License-Identifier: Apache-2.0
// Generated by scripts/gen-icons.mjs from lucide-static ${version}. Do not edit.
//
// Icons are from Lucide (ISC License, Copyright (c) Lucide Icons and Contributors).
// ${derived.join(", ")} derive from Feather
// (MIT License, Copyright (c) 2013-present Cole Bemis).
// Full license texts are in THIRD_PARTY_NOTICES.md.

export const ICONS: Readonly<Record<string, string>> = {
${entries.join("\n")}
};
`;

emit("src/render/generated/icons.ts", out);
