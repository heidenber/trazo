import type { Scene } from "../scene.js";
import { FAVICON_SVG } from "./brand.js";
import { VERSION } from "../version.js";
import { INTER_400_WOFF2_BASE64, INTER_600_WOFF2_BASE64 } from "./generated/font.js";
import { escapeXml, renderSvg } from "./svg.js";
import { chromeHtml, embeddedSource, inertJson } from "./chrome.js";
import { pageCss } from "./theme.js";
import { CREDIT_STRIP, VIEWER_SCRIPT } from "./viewer.js";

const ATTRIBUTION = `Generated by trazo ${VERSION}. Icons: Lucide (ISC License), portions derived from Feather (MIT License, Copyright (c) 2013-present Cole Bemis). Font: Inter (SIL Open Font License 1.1, Copyright 2016 The Inter Project Authors).`;

export { SOURCE_CAP } from "./chrome.js";

export interface HtmlOptions {
  /** The normalized input, embedded as JSON for "Copy JSON source" when it is at most SOURCE_CAP bytes. */
  source?: unknown;
}

/** Margin around the diagram on the printed page, in CSS pixels. */
const PRINT_MARGIN = 24;

/**
 * The printed page takes the diagram's own size, so "Save as PDF" yields one page that holds
 * the whole diagram with no empty band. Chrome and Edge honor it; other browsers may fall back
 * to their default paper, where the diagram still scales to fit.
 */
function printPage(scene: Scene): string {
  const w = Math.ceil(scene.width) + 2 * PRINT_MARGIN;
  const h = Math.ceil(scene.height) + CREDIT_STRIP + 2 * PRINT_MARGIN;
  return `\n@page { size: ${w}px ${h}px; margin: ${PRINT_MARGIN}px; }\n`;
}

export function renderHtml(scene: Scene, options: HtmlOptions = {}): string {
  const title = escapeXml(scene.title);
  const source = embeddedSource(options.source);
  const details = scene.nodes.filter((n) => n.detail !== undefined);
  const detail =
    details.length === 0
      ? undefined
      : inertJson(Object.fromEntries(details.map((n) => [n.id, n.detail])));
  const page = chromeHtml({
    title: scene.title,
    ...(scene.description === undefined ? {} : { description: scene.description }),
    theme: scene.theme,
    width: scene.width,
    height: scene.height,
    flow:
      scene.type !== "erd" &&
      scene.type !== "chen" &&
      scene.type !== "state" &&
      scene.type !== "class",
    svg: renderSvg(scene),
    ...(source === undefined ? {} : { source }),
    ...(detail === undefined ? {} : { detail }),
  });
  return `<!doctype html>
<!-- ${ATTRIBUTION} -->
<html lang="en" data-theme="${scene.theme}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="generator" content="trazo ${VERSION}">
<title>${title}</title>
<link rel="icon" type="image/svg+xml" href="data:image/svg+xml,${encodeURIComponent(FAVICON_SVG)}">
<style>${pageCss(INTER_400_WOFF2_BASE64, INTER_600_WOFF2_BASE64)}${printPage(scene)}</style>
</head>
<body>
${page}
<footer class="credit"><a href="https://github.com/heidenber/trazo" target="_blank" rel="noopener noreferrer">Made with trazo</a></footer>
<script>${VIEWER_SCRIPT}</script>
</body>
</html>
`;
}
